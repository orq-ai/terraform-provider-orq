var (
	_ resource.Resource                = &auditLogDestinationResource{}
	_ resource.ResourceWithConfigure   = &auditLogDestinationResource{}
	_ resource.ResourceWithImportState = &auditLogDestinationResource{}
)

func NewAuditLogDestinationResource() resource.Resource { return &auditLogDestinationResource{} }

type auditLogDestinationResource struct {
	destinations client.AuditLogDestinationsAPI
}

type auditLogDestinationResourceModel struct {
	ID                types.String `tfsdk:"id"`
	DisplayName       types.String `tfsdk:"display_name"`
	Description       types.String `tfsdk:"description"`
	URL               types.String `tfsdk:"url"`
	Status            types.String `tfsdk:"status"`
	SigningSecret     types.String `tfsdk:"signing_secret"`
	SigningSecretHint types.String `tfsdk:"signing_secret_hint"`
	SecretRotatedAt   types.String `tfsdk:"secret_rotated_at"`
	CreatedAt         types.String `tfsdk:"created_at"`
	UpdatedAt         types.String `tfsdk:"updated_at"`
}

func (r *auditLogDestinationResource) Metadata(_ context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_audit_log_destination"
}

func (r *auditLogDestinationResource) Schema(_ context.Context, _ resource.SchemaRequest, resp *resource.SchemaResponse) {
	resp.Schema = schema.Schema{
		MarkdownDescription: "A signed webhook destination that receives the workspace's audit log events. " +
			"Requires the audit logs feature on the workspace.",
		Attributes: map[string]schema.Attribute{
			"id": schema.StringAttribute{
				Computed:            true,
				MarkdownDescription: "Destination ID assigned by orq.",
				PlanModifiers:       []planmodifier.String{stringplanmodifier.UseStateForUnknown()},
			},
			"display_name": schema.StringAttribute{
				Required:            true,
				MarkdownDescription: "Destination name, unique within the workspace (1-255 characters).",
				Validators:          []validator.String{stringvalidator.LengthBetween(1, 255)},
			},
			"description": schema.StringAttribute{
				Optional:            true,
				MarkdownDescription: "Description of the receiving system (up to 1000 characters).",
				Validators:          []validator.String{stringvalidator.LengthAtMost(1000)},
			},
			"url": schema.StringAttribute{
				Required: true,
				MarkdownDescription: "Absolute HTTPS endpoint that receives the signed events. Private and loopback " +
					"addresses are rejected. The server only accepts a new URL while the destination is paused, so " +
					"changing it on an `ACTIVE` destination pauses deliveries, swaps the URL, and resumes them.",
				Validators: []validator.String{stringvalidator.LengthBetween(1, 2048)},
			},
			"status": schema.StringAttribute{
				Optional: true,
				Computed: true,
				Default:  stringdefault.StaticString(client.AuditLogDestinationStatusActive),
				MarkdownDescription: "`ACTIVE` (default) delivers events; `PAUSED` retains them and delivers the " +
					"backlog once the destination is active again.",
				Validators: []validator.String{
					stringvalidator.OneOf(client.AuditLogDestinationStatusActive, client.AuditLogDestinationStatusPaused),
				},
			},
			"signing_secret": schema.StringAttribute{
				Computed:  true,
				Sensitive: true,
				MarkdownDescription: "Secret for verifying delivery signatures. Generated by orq and returned only " +
					"on create, so it is null on an imported destination and stale after a rotation made outside Terraform.",
				PlanModifiers: []planmodifier.String{stringplanmodifier.UseStateForUnknown()},
			},
			"signing_secret_hint": schema.StringAttribute{
				Computed:            true,
				MarkdownDescription: "Last four characters of the current signing secret.",
				PlanModifiers:       []planmodifier.String{stringplanmodifier.UseStateForUnknown()},
			},
			"secret_rotated_at": schema.StringAttribute{
				Computed:            true,
				MarkdownDescription: "Time the current signing secret was issued (RFC 3339).",
				PlanModifiers:       []planmodifier.String{stringplanmodifier.UseStateForUnknown()},
			},
			"created_at": schema.StringAttribute{
				Computed:            true,
				MarkdownDescription: "Creation time (RFC 3339).",
				PlanModifiers:       []planmodifier.String{stringplanmodifier.UseStateForUnknown()},
			},
			"updated_at": schema.StringAttribute{
				Computed:            true,
				MarkdownDescription: "Last update time (RFC 3339).",
			},
		},
	}
}

func (r *auditLogDestinationResource) Configure(_ context.Context, req resource.ConfigureRequest, resp *resource.ConfigureResponse) {
	if req.ProviderData == nil {
		return
	}
	c, ok := req.ProviderData.(*client.Client)
	if !ok {
		resp.Diagnostics.AddError("Unexpected provider data type",
			fmt.Sprintf("Expected *client.Client, got %T. This is a provider bug.", req.ProviderData))
		return
	}
	r.destinations = c.AuditLogDestinations()
}

func (r *auditLogDestinationResource) apply(d *client.AuditLogDestination, m *auditLogDestinationResourceModel) {
	m.ID = types.StringValue(d.ID)
	m.DisplayName = types.StringValue(d.DisplayName)
	m.Description = preserveEmptyString(m.Description, d.Description)
	m.URL = types.StringValue(d.URL)
	m.Status = types.StringValue(d.Status)
	m.SigningSecretHint = types.StringValue(d.SigningSecretHint)
	m.SecretRotatedAt = types.StringValue(d.SecretRotatedAt)
	m.CreatedAt = types.StringValue(d.CreatedAt)
	m.UpdatedAt = types.StringValue(d.UpdatedAt)
}

func (r *auditLogDestinationResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan auditLogDestinationResourceModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	resp.Diagnostics.Append(revalidatePlan(ctx, req.Plan)...)
	if resp.Diagnostics.HasError() {
		return
	}

	created, signingSecret, err := r.destinations.Create(ctx, client.AuditLogDestinationCreateInput{
		DisplayName: plan.DisplayName.ValueString(),
		Description: plan.Description.ValueString(),
		URL:         plan.URL.ValueString(),
	})
	if err != nil {
		resp.Diagnostics.AddError("Unable to create audit log destination", errDetail(err))
		return
	}
	plannedStatus := plan.Status.ValueString()
	plan.SigningSecret = types.StringValue(signingSecret)
	r.apply(created, &plan)
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)

	// Create always yields an active destination; the state above keeps the secret if pausing fails.
	if resp.Diagnostics.HasError() || plannedStatus == created.Status {
		return
	}
	paused, err := r.destinations.Update(ctx, client.AuditLogDestinationUpdateInput{ID: created.ID, Status: &plannedStatus})
	if err != nil {
		resp.Diagnostics.AddError("Unable to set audit log destination status", errDetail(err))
		return
	}
	r.apply(paused, &plan)
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

func (r *auditLogDestinationResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var state auditLogDestinationResourceModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	d, err := r.destinations.Get(ctx, state.ID.ValueString())
	if err != nil {
		if isNotFound(err) {
			resp.State.RemoveResource(ctx)
			return
		}
		resp.Diagnostics.AddError("Unable to read audit log destination", errDetail(err))
		return
	}
	r.apply(d, &state)
	resp.Diagnostics.Append(resp.State.Set(ctx, &state)...)
}

func (r *auditLogDestinationResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var plan, state auditLogDestinationResourceModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	resp.Diagnostics.Append(revalidatePlan(ctx, req.Plan)...)
	if resp.Diagnostics.HasError() {
		return
	}

	name := plan.DisplayName.ValueString()
	description := plan.Description.ValueString()
	status := plan.Status.ValueString()
	patch := client.AuditLogDestinationUpdateInput{
		ID:          plan.ID.ValueString(),
		DisplayName: &name,
		Description: &description,
		Status:      &status,
	}
	if !plan.URL.Equal(state.URL) {
		patch.URL = strPtr(plan.URL)
	}

	d, err := r.updateWithURLPause(ctx, patch)
	if err != nil {
		resp.Diagnostics.AddError("Unable to update audit log destination", errDetail(err))
		return
	}
	plan.SigningSecret = state.SigningSecret
	r.apply(d, &plan)
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

func (r *auditLogDestinationResource) updateWithURLPause(ctx context.Context, patch client.AuditLogDestinationUpdateInput) (*client.AuditLogDestination, error) {
	if patch.URL == nil || *patch.Status == client.AuditLogDestinationStatusPaused {
		return r.destinations.Update(ctx, patch)
	}
	resumed := patch.Status
	paused := client.AuditLogDestinationStatusPaused
	patch.Status = &paused
	if _, err := r.destinations.Update(ctx, patch); err != nil {
		return nil, err
	}
	return r.destinations.Update(ctx, client.AuditLogDestinationUpdateInput{ID: patch.ID, Status: resumed})
}

func (r *auditLogDestinationResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var state auditLogDestinationResourceModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	if err := r.destinations.Delete(ctx, state.ID.ValueString()); err != nil {
		if isNotFound(err) {
			return
		}
		resp.Diagnostics.AddError("Unable to delete audit log destination", errDetail(err))
	}
}

func (r *auditLogDestinationResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	resource.ImportStatePassthroughID(ctx, path.Root("id"), req, resp)
}
